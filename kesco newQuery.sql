SELECT (SELECT  COUNT(DISTINCT MTR_NUMBER) FROM CIS.BELOW_ZERO_NOTIFICATION BN WHERE 
BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='0' AND  BN.DELIVERY_STATUS IS NULL AND BN.METER_STATUS='DISCONNECT' AND BN.TRANSACTION_ID IS NULL
AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()-1))) PENDING
,(SELECT  COUNT(DISTINCT MTR_NUMBER)  FROM CIS.BELOW_ZERO_NOTIFICATION BN WHERE 
BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='1' AND  BN.DELIVERY_STATUS='SUCCESS' AND BN.METER_STATUS='DISCONNECT' AND BN.TRANSACTION_ID IS NOT NULL
AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()-1))) SUCCESS
,(SELECT  COUNT(DISTINCT MTR_NUMBER)  FROM CIS.BELOW_ZERO_NOTIFICATION BN WHERE 
BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='1' AND  BN.DELIVERY_STATUS='FAILED' AND BN.METER_STATUS='DISCONNECT' AND BN.TRANSACTION_ID IS NOT NULL
AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()-1))) FAILED
,(SELECT  COUNT(DISTINCT MTR_NUMBER)  FROM CIS.BELOW_ZERO_NOTIFICATION BN WHERE 
BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='1' AND  BN.DELIVERY_STATUS='ABORTED' AND BN.METER_STATUS='DISCONNECT' AND BN.TRANSACTION_ID IS NOT NULL
AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()-1))) ABORTED
,(SELECT  COUNT(DISTINCT MTR_NUMBER)  FROM CIS.BELOW_ZERO_NOTIFICATION BN WHERE 
BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='S' AND  BN.DELIVERY_STATUS IS NULL  AND BN.METER_STATUS='DISCONNECT' AND BN.TRANSACTION_ID IS NOT NULL
AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()-1))) PENDING_HES_RESPONSE




