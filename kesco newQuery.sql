/*  DLP */


SELECT SUM(DLP_08HRS)'DLP @ 08:00 Hrs',SUM(DLP_12HRS) 'DLP @ 12:00 Hrs',SUM(DLP_24HRS)'DLP @ 24:00 Hrs' FROM (
SELECT  
CONVERT(VARCHAR,METER_TIME,112) AS METER_TIME,
CASE  WHEN CREATE_DATE  BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' and convert(varchar,getdate()-1,23)+' '+'07:59:59'  THEN COUNT(DISTINCT METER_NUMBER) ELSE 0 END  AS DLP_08HRS,
CASE  WHEN CREATE_DATE  BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' and convert(varchar,getdate()-1,23)+' '+'11:59:59'  THEN COUNT(DISTINCT METER_NUMBER) ELSE 0 END  AS DLP_12HRS,
CASE  WHEN CREATE_DATE  BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' and convert(varchar,getdate()-1,23)+' '+'23:59:59'  THEN COUNT(DISTINCT METER_NUMBER) ELSE 0 END  AS DLP_24HRS
FROM FEP.FEP_CSV_ED (NOLOCK)
WHERE METER_TIME BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' AND convert(varchar,getdate()-1,23)+' '+'23:59:59' AND STATUS='Success'
GROUP BY CREATE_DATE,METER_TIME
) QQ GROUP BY METER_TIME


/*  BLP */


SELECT SUM(BLP_08HRS)'BLP @ 08:00 Hrs',SUM(BLP_12HRS) 'BLP @ 12:00 Hrs',SUM(BLP_24HRS)'BLP @ 24:00 Hrs' FROM (
SELECT  CONVERT(VARCHAR,METER_TIME,112) AS METER_TIME,
CASE  WHEN CREATE_DATE  BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' and convert(varchar,getdate()-1,23)+' '+'07:59:59' THEN COUNT(DISTINCT METER_NUMBER) ELSE 0 END  AS BLP_08HRS,
CASE  WHEN CREATE_DATE  BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' and convert(varchar,getdate()-1,23)+' '+'11:59:59'  THEN COUNT(DISTINCT METER_NUMBER) ELSE 0 END  AS BLP_12HRS,
CASE  WHEN CREATE_DATE  BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' and convert(varchar,getdate()-1,23)+' '+'23:59:59'  THEN COUNT(DISTINCT METER_NUMBER) ELSE 0 END  AS BLP_24HRS
FROM FEP.FEP_CSV_LP (NOLOCK)
WHERE METER_TIME BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' AND convert(varchar,getdate()-1,23)+' '+'23:59:59' AND STATUS='Success'
GROUP BY CREATE_DATE,METER_TIME
) QQ GROUP BY METER_TIME

/*  EOB */


