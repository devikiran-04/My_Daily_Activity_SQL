--Abstract Opening Balance and Closing Balance Report:-
--***************************************************

WITH A AS (
SELECT BMETER_NUM ,FINAL_BALANCE AS PRESENT_FINAL,AVAL_BALANCE AS PRESENT_AVAL FROM CIS.BILL_DETAILS_T (NOLOCK)  WHERE
 BLISSUE_DT BETWEEN convert(varchar,getdate()-1,23)+' '+'00:00:00' AND convert(varchar,getdate()-1,23)+' '+'23:59:59'
--AND BMETER_NUM='LT2525323'
),B AS (
SELECT BMETER_NUM,FINAL_BALANCE AS PAST_FINAL,AVAL_BALANCE AS PAST_AVAL FROM CIS.BILL_DETAILS_T (NOLOCK) WHERE BLISSUE_DT 
BETWEEN convert(varchar,getdate()-2,23)+' '+'00:00:00' AND convert(varchar,getdate()-2,23)+' '+'23:59:59'
AND BMETER_NUM IN (SELECT BMETER_NUM FROM A)
) --SELECT * FROM B
SELECT COUNT(BMETER_NUM) 'Mismatch Count',SUM(CLOSING_BALANCE) AS 'Closing Balance',SUM(ISNULL(Recharge_Amount,0)) Recharge_Amount, SUM(OPENING_BALACE) AS 'Opening Balance' 
from (
SELECT * FROM (
SELECT BMETER_NUM,CLOSING_BALANCE,Recharge_Amount,OPENING_BALACE,ROUND(ABS(OPENING_BALACE-(CLOSING_BALANCE)-Recharge_Amount),0,3) DIFF FROM (
SELECT BMETER_NUM,CLOSING_BALANCE,SUM(Recharge_Amount) Recharge_Amount,OPENING_BALACE,SUM(DIFF) DIFF FROM (
select BMETER_NUM,CLOSING_BALANCE,Recharge_Amount,OPENING_BALACE,ROUND(ABS(OPENING_BALACE-(CLOSING_BALANCE)-Recharge_Amount),0,3) DIFF FROM (
SELECT  A.BMETER_NUM, B.PAST_FINAL CLOSING_BALANCE,RH.Recharge_Amt Recharge_Amount,A.PRESENT_AVAL OPENING_BALACE 
FROM A INNER JOIN B ON A.BMETER_NUM=B.BMETER_NUM
LEFT OUTER JOIN CIS.MDM_MTR_RECHARGE_HISTORY RH (NOLOCK) ON RH.MTR_NUMBER=A.BMETER_NUM AND RH.RECORD_STATUS=1
AND RH.DT_OF_RECHARGE BETWEEN convert(varchar,getdate()-2,23)+' '+'00:00:00' AND convert(varchar,getdate()-1,23)+' '+'23:59:59'
WHERE  A.PRESENT_AVAL<>B.PAST_FINAL
)ZX
)G GROUP BY BMETER_NUM,CLOSING_BALANCE,OPENING_BALACE
)GH 
)FG WHERE (DIFF is null or DIFF<>'0.0000')
)HK





