SELECT 'HES_EOB' DATA_TYPE,COUNT(DISTINCT METER_NUMBER) CNT,COUNT(METER_NUMBER) TOT_CNT,COUNT(METER_NUMBER)-COUNT(DISTINCT METER_NUMBER) DUP 
FROM FEP.FEP_CSV_EOB_ED (NOLOCK) WHERE STATUS='SUCCESS' AND METER_TIME=CONVERT(VARCHAR,DATEADD(month, DATEDIFF(month, 0, getdate()), 0),112)
UNION ALL
SELECT 'M_EOB_ACTUAL' DATA_TYPE,COUNT(DISTINCT MTR_NUMBER) CNT,COUNT(MTR_NUMBER) TOT_CNT,COUNT(MTR_NUMBER)-COUNT(DISTINCT MTR_NUMBER) DUP FROM MDMS.MDM_EOB_DATA (NOLOCK) WHERE READ_DATE =CONVERT(VARCHAR,DATEADD(month, DATEDIFF(month, 0, getdate()), 0),112) AND READ_TIME=0 AND D_TYPE=1 AND IS_ESTIMATED=0 AND RECORD_STATUS = 1
UNION ALL
SELECT 'M_EOBD' DATA_TYPE,COUNT(DISTINCT MTR_NUMBER) CNT,COUNT(MTR_NUMBER) TOT_CNT,COUNT(MTR_NUMBER)-COUNT(DISTINCT MTR_NUMBER) DUP
FROM MDMS.MDM_EOB_DMD (NOLOCK) WHERE READ_DATE =CONVERT(VARCHAR,DATEADD(month, DATEDIFF(month, 0, getdate()), 0),112) AND D_TYPE=2 AND RECORD_STATUS = 1
UNION ALL
SELECT 'BILLING_VIEW_ACTUAL' DATA_TYPE,COUNT(DISTINCT METER_NUMBER) CNT,COUNT(METER_NUMBER) TOT_CNT,COUNT(METER_NUMBER)-COUNT(DISTINCT METER_NUMBER) DUP
FROM MDMS.MDM_MONTHLY_BILLING_VIEW (NOLOCK) WHERE LP_DATE =CONVERT(VARCHAR,DATEADD(month, DATEDIFF(month, 0, getdate()), 0),112)
AND EST_FLAG='ACTUAL'



