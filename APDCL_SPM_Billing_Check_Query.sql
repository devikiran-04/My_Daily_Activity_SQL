SELECT 
DT, TOTAL_PREPAID, BS AS BILL_STOPPED, (TOTAL_PREPAID - BS) AS LIVE_METERS,ED_CNT, BILLING_CNT, UN_BILLED_CNT
FROM (SELECT DT,(SELECT COUNT(DISTINCT A.METER_NUMBER) FROM SPM.PREPAID_CONSDETAILS_T A 
WHERE A.RECORD_STATUS = 1   
AND A.CONS_TYPE = 'PRE' 
AND A.CREATE_DATE::DATE <= DT) AS TOTAL_PREPAID,        
(SELECT COUNT(DISTINCT A.METER_NUMBER) 
FROM SPM.PREPAID_CONSDETAILS_T A          
WHERE A.RECORD_STATUS = 1            
AND A.CONS_TYPE = 'PRE' 
AND A.BILLING_STATUS = 'BS'            
AND A.CREATE_DATE::DATE <= DT) AS BS,        
ED_CNT,        
BILLING_CNT,        
UN_BILLED_CNT
FROM (SELECT DT, ED_CNT, BILLING_CNT, (ED_CNT - BILLING_CNT) AS UN_BILLED_CNT
FROM (SELECT (ENC.BILL_DATE - INTERVAL '1 day')::DATE AS DT, COUNT(DISTINCT ENC.MTR_NUMBER) AS ED_CNT,
COUNT(DISTINCT BILL.METER_NUMBER) AS BILLING_CNT          
FROM SPM.PREPAID_CONSDETAILS_T A       
INNER JOIN SPM.MDM_ENERGY_DATA_CLONE ENC 
ON A.METER_NUMBER = ENC.MTR_NUMBER      
AND A.RECORD_STATUS = 1                 
AND A.CONS_TYPE = 'PRE'                 
AND A.BILLING_STATUS = 'L'
AND ENC.RECORD_STATUS = 1 
LEFT JOIN SPM.SPM_BILL_DETAILS_T BILL ON A.METER_NUMBER = BILL.METER_NUMBER 
AND BILL.RECORD_STATUS = 1                
AND (BILL.BLISSUE_DT + INTERVAL '1 day') = ENC.BILL_DATE
WHERE ENC.BILL_DATE::DATE BETWEEN CURRENT_DATE - INTERVAL '6 days' AND CURRENT_DATE            
GROUP BY (ENC.BILL_DATE - INTERVAL '1 day')::DATE 
) H ) Z ) A ORDER BY DT ASC;