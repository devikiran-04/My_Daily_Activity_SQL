(SELECT 'TODAY_CONNECTED_COUNT --' AS TYPE, COUNT(distinct mtr_number) as COUNT FROM CIS.BELOW_ZERO_NOTIFICATION BN (NOLOCK) WHERE

BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='1' AND BN.DELIVERY_STATUS='SUCCESS' AND BN.METER_STATUS='CONNECT' AND BN.TRANSACTION_ID IS NOT NULL

AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()))) --AS TODAY_CONNECTED_COUNT

UNION ALL

(SELECT 'TODAY_DISCONNECTED_COUNT -- ' AS TYPE,COUNT(distinct mtr_number) as COUNT FROM CIS.BELOW_ZERO_NOTIFICATION BN (NOLOCK) WHERE

BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='1' AND BN.DELIVERY_STATUS='SUCCESS' AND BN.METER_STATUS='DISCONNECT' AND BN.TRANSACTION_ID IS NOT NULL

AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()))) --AS TODAY_DISCONNECTED_COUNT

UNION ALL

(SELECT 'PENDING_CONNECT_COUNT -- ' AS TYPE,COUNT(distinct(BN.MTR_NUMBER)) as COUNT FROM CIS.BELOW_ZERO_NOTIFICATION BN WHERE

BN.RECORD_STATUS=1 AND BN.EVENT_STATUS='1' AND BN.DELIVERY_STATUS='FAILED' AND BN.METER_STATUS='CONNECT' AND BN.TRANSACTION_ID IS NOT NULL

AND DATEADD(DD,0,DATEDIFF(DD,0,UPDATE_DATE)) = DATEADD(DD,0,DATEDIFF(DD,0,GETDATE()))) --AS PENDING_CONNECT_COUNT

UNION ALL

(SELECT 'PENDING_DISCONNECT_COUNT -- ' AS TYPE,COUNT(distinct(BN.MTR_NUMBER)) as COUNT

FROM CIS.BELOW_ZERO_NOTIFICATION BN (nolock) WHERE BN.RECORD_STATUS='1' AND BN.EVENT_STATUS='0' AND BN.METER_STATUS='DISCONNECT') --AS PENDING_DISCONNECT_COUNT

UNION ALL

(SELECT 'TODAY_HES_CONNECTED_COUNT -- ' AS TYPE,COUNT(distinct FEP.METER_NUMBER) as COUNT FROM FEP.FEP_ONDEMAND FEP (NOLOCK) LEFT JOIN KETTLE.FEP_ONDEMAND_TEMP KT (NOLOCK)

