UNION ALL

(SELECT 'TODAY_HES_DISCONNECTED_COUNT -- ' AS TYPE,COUNT(distinct FEP.METER_NUMBER) as COUNT FROM FEP.FEP_ONDEMAND FEP (NOLOCK) LEFT JOIN KETTLE.FEP_ONDEMAND_TEMP KT (NOLOCK)

--SELECT * FROM FEP.FEP_ONDEMAND FEP (NOLOCK) LEFT JOIN KETTLE.FEP_ONDEMAND_TEMP KT (NOLOCK)

